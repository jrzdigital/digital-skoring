export type MatchCategory = 'tanding' | 'jurus';
export type JurusSubCategory = 'tunggal' | 'ganda' | 'regu' | 'solo_kreatif';
export type CornerColor = 'merah' | 'biru';

export type PenaltyType = 
  | 'binaan' 
  | 'teguran1' 
  | 'teguran2' 
  | 'peringatan1' 
  | 'peringatan2' 
  | 'diskualifikasi';

export type VictoryType = 
  | 'angka' 
  | 'mutlak' 
  | 'wmp' // Wasit Menghentikan Pertandingan
  | 'teknik' 
  | 'diskualifikasi' 
  | 'undur_diri';

export interface Competitor {
  id: string;
  name: string;
  contingent: string; // Kontingen / Daerah / Perguruan
  weightClass: string; // e.g. "Kelas C (55 - 60 kg) Putra"
}

export interface ScoreAction {
  id: string;
  timestamp: number;
  round: number;
  corner: CornerColor;
  actionType: 'pukulan' | 'tendangan' | 'jatuhan' | 'kuncian' | 'hukuman' | 'teguran1' | 'teguran2' | 'peringatan1' | 'peringatan2';
  points: number;
  description: string;
  judgesConfirmed: number[]; // e.g. [1, 2] juri yang memvalidasi
  isConsensus: boolean;
  isAutoGenerated?: boolean;
}

export interface RoundScore {
  pukulan: number;
  tendangan: number;
  jatuhan: number;
  kuncian: number;
  hukuman: number;
  total: number;
}

export interface JudgeVote {
  judgeId: number; // 1 to 5
  corner: CornerColor;
  actionType: 'pukulan' | 'tendangan' | 'jatuhan' | 'kuncian';
  timestamp: number;
}

export interface TandingMatchState {
  arena: string; // e.g. "Gelanggang A"
  matchNumber: string; // e.g. "Partai 24"
  gender: 'Putra' | 'Putri';
  ageGroup: 'Usia Dini' | 'Pra Remaja' | 'Remaja' | 'Dewasa' | 'Master';
  weightClass: string;
  currentRound: number; // 1, 2, 3
  totalRounds: number;
  roundDurationSeconds: number; // default 120 (2 mins)
  remainingSeconds: number;
  isTimerRunning: boolean;
  status: 'persiapan' | 'berlangsung' | 'istirahat' | 'selesai';
  
  redCorner: Competitor;
  blueCorner: Competitor;
  
  // Scores per round
  redScores: [RoundScore, RoundScore, RoundScore];
  blueScores: [RoundScore, RoundScore, RoundScore];
  
  // Penalties
  redPenalties: {
    binaan: number;
    teguran: number; // 0, 1, 2
    peringatan: number; // 0, 1, 2
    isDisqualified: boolean;
  };
  bluePenalties: {
    binaan: number;
    teguran: number;
    peringatan: number;
    isDisqualified: boolean;
  };

  // Active consensus window
  activeVotes: JudgeVote[];
  recentActions: ScoreAction[];
  
  // Jurors count (3 or 5)
  judgeCount: 3 | 5;
  activeJudges: number[]; // [1, 2, 3] or [1, 2, 3, 4, 5]

  // Winner declaration
  winner: CornerColor | null;
  winType: VictoryType | null;
  notes: string;
}

export interface JurusJudgeScore {
  judgeId: number;
  judgeName: string;
  kebenaran: number; // Base 9.90 minus deductions
  kemantapan: number; // 0.01 - 0.10
  kesalahanCount: number; // total mistake clicks (-0.01 each)
  total: number;
}

export interface JurusMatchState {
  arena: string;
  matchNumber: string;
  subCategory: JurusSubCategory;
  competitor: {
    id: string;
    name: string;
    contingent: string;
    categoryTitle: string;
  };
  targetDurationSeconds: number; // 180s for standard Tunggal/Ganda/Regu
  elapsedSeconds: number;
  isTimerRunning: boolean;
  isFinished: boolean;
  
  // Deductions outside movement
  timePenalty: number; // automatically calculated
  senjataJatuhPenalty: number; // -0.10
  keluarGelanggangPenalty: number; // -0.05
  pakaianPenalty: number; // -0.05
  
  // 5 judges scores
  judges: JurusJudgeScore[];
  
  // Computed final result
  finalScore: number;
  rank: number;
  medianScore: number;
}

export type ViewRole = 'operator' | 'big_screen' | 'judge_tablet' | 'jurus_panel';

export interface SyncPacket {
  version: string;
  timestamp: number;
  sender: string;
  category: MatchCategory;
  tanding?: TandingMatchState;
  jurus?: JurusMatchState;
  activeRole?: ViewRole;
  selectedJudgeId?: number;
}
